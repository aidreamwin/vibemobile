/** Entry point for the one-line installers, after the release has been verified and extracted. */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import readline from 'node:readline'
import { Writable } from 'node:stream'
import { fileURLToPath } from 'node:url'
import {
  checkPort,
  copyTree,
  ecosystemCwd,
  ensureDir,
  fail,
  hasCommand,
  isWindows,
  log,
  one,
  parseArgs,
  pm2BinPath,
  pm2Delete,
  pm2Describe,
  pm2Start,
  portIsFree,
  readEnvFile,
  readJson,
  readRelease,
  releaseStamp,
  run,
  runNpm,
  step,
  waitForHub,
  waitForPortListening,
  waitForPortsFree,
  warn,
  writeActiveRelease,
  writeAtomic,
} from './lib/common.mjs'
import { lockInstall } from './lib/job.mjs'

const SOURCE = path.resolve(fileURLToPath(new URL('..', import.meta.url)))
const release = readRelease(SOURCE)
const role = release?.contents
if (role !== 'hub' && role !== 'runner') fail('Run this installer from a Hub or Runner release package.')

const args = parseArgs()
const option = (name) => one(args[name])
const flag = (name) => option(name) === true || option(name) === 'true'
const noStart = flag('noStart')
const defaultName = role === 'hub' ? 'vibemobile' : 'vibemobile-runner'
const localPrefix = isWindows
  ? path.join(process.env.APPDATA || os.homedir(), 'npm')
  : path.join(os.homedir(), '.local')
process.env.PATH = `${process.env.PATH}${path.delimiter}${isWindows ? localPrefix : path.join(localPrefix, 'bin')}`

const dataHome = isWindows ? process.env.LOCALAPPDATA : process.env.XDG_DATA_HOME
const defaultTarget = path.join(dataHome || path.join(os.homedir(), '.local', 'share'), 'vibemobile', role)
const explicitTarget = option('target')
const requestedName = String(option('pm2Name') ?? defaultName)

function installedEnv(root) {
  const env = readEnvFile(path.join(root, 'vibemobile.env'))
  return Object.keys(env).length ? env : null
}

function installedRole(env) {
  return env.VIBEMOBILE_ROLE === 'runner' || env.VIBEMOBILE_HUB_URL ? 'runner' : 'hub'
}

function findApp(name) {
  return pm2BinPath() || hasCommand('pm2') ? pm2Describe(name) : undefined
}

function appRoot(app) {
  const env = app?.pm2_env
  const root = env?.VIBEMOBILE_INSTALL_DIR ?? env?.env?.VIBEMOBILE_INSTALL_DIR ?? env?.pm_cwd
  return root ? path.resolve(root) : null
}

async function question(prompt, secret = false) {
  if (!process.stdin.isTTY) fail('Interactive input requires a terminal. Supply installer options for unattended use.')
  const output = secret
    ? new Writable({
        write(_chunk, _encoding, callback) {
          callback()
        },
      })
    : process.stdout
  if (secret) process.stdout.write(prompt)
  try {
    return await new Promise((resolve, reject) => {
      const reader = readline.createInterface({ input: process.stdin, output, terminal: true, historySize: 0 })
      let answered = false
      reader.on('SIGINT', () => reader.close())
      reader.on('close', () => {
        if (!answered) reject(new Error('Installation cancelled.'))
      })
      reader.question(secret ? '' : prompt, (answer) => {
        answered = true
        reader.close()
        resolve(answer.trim())
      })
    })
  } finally {
    if (secret) process.stdout.write('\n')
  }
}

async function input(prompt, value, validate, secret = false) {
  if (value !== undefined) return validate(String(value))
  for (;;) {
    const answer = await question(prompt, secret)
    try {
      return validate(answer)
    } catch (error) {
      warn(error.message)
    }
  }
}

function hubAddress(value) {
  try {
    const url = new URL(value.includes('://') ? value : `ws://${value}`)
    if (url.protocol === 'http:') url.protocol = 'ws:'
    if (url.protocol === 'https:') url.protocol = 'wss:'
    if (['ws:', 'wss:'].includes(url.protocol) && url.hostname && !url.username && !url.password) {
      return `${url.protocol}//${url.host}`
    }
  } catch {
    // Invalid input gets the same short message, without echoing its contents.
  }
  fail('Enter a valid Hub address, for example http://192.168.1.10:3000 or https://hub.example.com.')
}

function runnerId(value) {
  if (!/^[a-zA-Z0-9_-]{1,64}$/.test(value)) fail('Runner ID must contain 1–64 letters, digits, underscores or hyphens.')
  return value
}

function credentials(value) {
  // Settings can supply a single ID:token credential. Existing raw tokens and
  // files containing the two legacy environment variables also work.
  const match = value.match(/^([a-zA-Z0-9_-]{1,64}):([^\r\n]+)$/)
  const id = match?.[1] ?? value.match(/^VIBEMOBILE_RUNNER_ID=(.+)$/m)?.[1]?.trim()
  const token = (match?.[2] ?? value.match(/^VIBEMOBILE_RUNNER_TOKEN=(.+)$/m)?.[1] ?? value).trim()
  if (token.length < 32 || /\s/.test(token)) fail('Enter the connection token generated by the Hub.')
  return { id, token }
}

async function runnerOptions(secretDir) {
  const url = await input('Hub address: ', option('hubUrl'), hubAddress)
  const tokenFile = option('runnerTokenFile')
  const value = tokenFile ? fs.readFileSync(path.resolve(String(tokenFile)), 'utf8').trim() : undefined
  const connection = await input('Connection token (ID:token or token): ', value, credentials, true)
  const id = await input('Runner ID: ', option('runnerId') ?? connection.id, runnerId)
  if (connection.id && id !== connection.id) fail('Runner ID does not match the connection token.')
  const privateTokenFile = path.join(secretDir, 'runner-token')
  fs.writeFileSync(privateTokenFile, connection.token, { mode: 0o600, flag: 'wx' })
  const options = [`--hub-url=${url}`, `--runner-id=${id}`, `--runner-token-file=${privateTokenFile}`]
  let ca = option('hubCa')
  if (ca === undefined && url.startsWith('wss:') && process.stdin.isTTY) {
    ca = await question('Private CA certificate path (Enter for a public certificate): ')
  }
  if (ca) options.push(`--hub-ca=${path.resolve(String(ca))}`)
  return options
}

function ensureBuildTools() {
  if (process.platform !== 'linux') return
  const missing = ['python3', 'make', 'g++'].filter((tool) => !hasCommand(tool))
  if (!missing.length) return
  const managers = [
    ['apt-get', ['install', '-y', 'build-essential', 'python3']],
    ['dnf', ['install', '-y', 'gcc-c++', 'make', 'python3']],
    ['yum', ['install', '-y', 'gcc-c++', 'make', 'python3']],
    ['apk', ['add', '--no-cache', 'build-base', 'python3']],
  ]
  const manager = managers.find(([command]) => hasCommand(command))
  const root = process.getuid?.() === 0
  if (!manager || (!root && !hasCommand('sudo'))) {
    fail(`Install the missing build dependencies (${missing.join(', ')}) with your system package manager and retry.`)
  }
  const [command, installArgs] = manager
  const execute = (argv) => (root ? run(command, argv) : run('sudo', [command, ...argv]))
  step('Installing native build dependencies')
  if (command === 'apt-get') execute(['update'])
  execute(installArgs)
}

function ensurePm2() {
  if (noStart || pm2BinPath() || hasCommand('pm2')) return
  step('Installing PM2 for the current user')
  runNpm(['install', '-g', 'pm2', '--prefix', localPrefix, '--no-audit', '--no-fund'])
}

function currentRelease(target) {
  const ecosystem = path.join(target, 'ecosystem.config.cjs')
  if (!fs.existsSync(ecosystem)) fail(`Missing PM2 configuration: ${ecosystem}`)
  const active = ecosystemCwd(fs.readFileSync(ecosystem, 'utf8')) ?? target
  return { ecosystem, active, release: readRelease(active) }
}

async function healthy(env, timeoutMs = 30_000) {
  if (role === 'hub') {
    await waitForHub({
      port: Number(env.PORT ?? 3000),
      tls: env.VIBEMOBILE_HUB_TLS === 'on',
      caPath: env.VIBEMOBILE_HUB_CA_FILE,
      timeoutMs,
    })
  } else {
    await waitForPortListening(Number(env.VIBEMOBILE_RUNNER_PORT ?? 5901), timeoutMs)
  }
}

function installationArgs(target, name) {
  const result = [
    `--role=${role}`,
    `--install-dir=${target}`,
    `--workspace=${option('workspace') ?? process.cwd()}`,
    `--pm2-name=${name}`,
  ]
  for (const name of [
    'port',
    'runner-port',
    'codex-port',
    'opencode-port',
    'pin',
    'pin-file',
    'public-host',
    'public-origin',
  ]) {
    const value = args[name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())]
    for (const item of value === undefined ? [] : [value].flat()) result.push(`--${name}=${item}`)
  }
  for (const name of ['tls', 'allow-root', 'no-start', 'no-terminal']) {
    if (flag(name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase()))) result.push(`--${name}`)
  }
  return result
}

async function checkPorts() {
  const hubPort = Number(option('port') ?? 3000)
  const ports = [
    ...(role === 'hub' ? [hubPort] : []),
    Number(option('runnerPort') ?? (role === 'hub' ? hubPort + 1 : 5901)),
    Number(option('codexPort') ?? 6900),
    Number(option('opencodePort') ?? 6920),
  ]
  for (const port of ports) checkPort(port, 'port')
  if (new Set(ports).size !== ports.length) fail('Service ports must be different.')
  if (!noStart) {
    for (const port of ports) {
      if (!(await portIsFree(port))) fail(`Port ${port} is in use. Choose another port with the installer options.`)
    }
  }
}

async function upgrade(target, env, name) {
  const current = currentRelease(target)
  log(`Installed ${role}: ${target}`)
  log(`Current: ${current.release?.serverVersion ?? 'unknown'} (${current.release?.commit ?? 'unknown'})`)
  log(`Release: ${release.serverVersion} (${release.commit})`)
  if (!flag('yes')) {
    if (!process.stdin.isTTY) fail('An existing installation was found. Run in a terminal or pass --yes to upgrade.')
    if (!/^y(es)?$/i.test(await question('Upgrade this installation? [y/N] '))) {
      log('Installation kept as is.')
      return
    }
  }

  if (current.release && releaseStamp(current.release, role) === releaseStamp(release, role)) {
    // A previous run may have written configuration before starting, or PM2
    // may have been stopped manually. Reuse the already built release.
    if (noStart) {
      log('This release is already installed.')
      return
    }
    const app = findApp(name)
    if (app?.pm2_env?.status === 'online' && path.relative(current.active, app.pm2_env.pm_cwd ?? target) === '') {
      try {
        await healthy(env, 5000)
        log('This release is already installed and running.')
        return
      } catch {
        warn('The installed service is not responding. Starting it again.')
      }
    }
    lockInstall(target)
    ensurePm2()
    step('Starting the installed release')
    if (app) pm2Delete(name)
    await waitForPortsFree([
      ...(role === 'hub' ? [Number(env.PORT ?? 3000)] : []),
      Number(env.VIBEMOBILE_RUNNER_PORT ?? 5901),
      Number(env.CODEX_PORT ?? 6900),
      Number(env.OPENCODE_PORT ?? 6920),
    ])
    pm2Start({ ecosystemFile: current.ecosystem, cwd: target, name, releaseDir: current.active })
    await healthy(env)
    writeActiveRelease(
      target,
      current.active,
      release,
      readJson(path.join(target, 'active-release.json'), {})?.previous,
      false,
    )
    log('VibeMobile is running.')
    return
  }

  ensureBuildTools()
  ensurePm2()
  run(process.execPath, [
    path.join(SOURCE, 'deploy', 'update.mjs'),
    `--target=${target}`,
    '--replace-release',
    ...(noStart ? ['--no-start'] : []),
  ])
}

async function install(target, name) {
  if (role === 'hub' && process.getuid?.() === 0 && !flag('allowRoot')) {
    fail('Run the installer as your normal user, or pass --allow-root if this is intended.')
  }
  const marker = path.join(target, '.quick-install.json')
  if (
    fs.existsSync(target) &&
    fs.readdirSync(target).some((entry) => entry !== 'install.lock') &&
    readJson(marker, {})?.role !== role
  ) {
    fail(`Installation directory is not empty: ${target}. Choose a dedicated directory with --target.`)
  }
  const secretDir = fs.mkdtempSync(path.join(os.tmpdir(), 'vibemobile-credentials-'))
  try {
    const options = installationArgs(target, name)
    if (role === 'runner') options.push(...(await runnerOptions(secretDir)))
    await checkPorts()
    ensureDir(target)
    lockInstall(target)
    if (installedEnv(target)) fail('An installation was created concurrently. Run the installer again to upgrade it.')
    writeAtomic(marker, `${JSON.stringify({ role })}\n`)
    const releaseDir = path.join(target, 'releases', releaseStamp(release, role))
    ensureBuildTools()
    ensurePm2()
    // Only an unfinished first install can reach this branch with an existing
    // release directory. Build afresh so a retry never mixes source versions.
    fs.rmSync(releaseDir, { recursive: true, force: true })
    copyTree(SOURCE, releaseDir)
    run(process.execPath, [path.join(releaseDir, 'deploy', 'install.mjs'), ...options])
    fs.rmSync(marker, { force: true })
  } finally {
    fs.rmSync(secretDir, { recursive: true, force: true })
  }
}

async function main() {
  let target = path.resolve(String(explicitTarget ?? defaultTarget))
  let env = installedEnv(target)
  // Discover existing PM2 installs even when they were originally extracted
  // into a custom directory. An explicit --target always wins.
  const app = findApp(env?.VIBEMOBILE_PM2_NAME ?? requestedName)
  const existingRoot = appRoot(app)
  if (!explicitTarget && !env && existingRoot && installedEnv(existingRoot)) {
    target = existingRoot
    env = installedEnv(target)
  }
  if (env && installedRole(env) !== role) fail(`This installation is a ${installedRole(env)}: ${target}`)
  const name = env?.VIBEMOBILE_PM2_NAME ?? requestedName
  if (existingRoot && path.relative(existingRoot, target) !== '') {
    fail(`PM2 app ${name} belongs to ${existingRoot}. Use its --target or choose a different --pm2-name.`)
  }
  if (app && !env) fail(`PM2 app ${name} already exists. Use --target to select its installation directory.`)
  if (env) await upgrade(target, env, name)
  else await install(target, name)
}

try {
  await main()
} catch (error) {
  console.error(`VibeMobile: ${error.message}`)
  process.exitCode = 1
}
